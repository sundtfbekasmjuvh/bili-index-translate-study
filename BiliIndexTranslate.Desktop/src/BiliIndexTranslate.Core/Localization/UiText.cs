namespace BiliIndexTranslate.Core.Localization;

/// <summary>
/// Interface text of the desktop app in English and Simplified Chinese. Both tables have the same keys;
/// {0}, {1} ... are filled in by <see cref="Translate"/>. Error details produced by the translation
/// core and the diagnostics log stay in English.
/// </summary>
public static partial class UiText
{
    public static IReadOnlyDictionary<string, string> English => En;
    public static IReadOnlyDictionary<string, string> SimplifiedChinese => Zh;

    /// <summary>Text for <paramref name="key"/> in <paramref name="language"/>; English when the language or the key is missing there, the key itself when unknown.</summary>
    public static string Translate(string? language, string key, params object?[] args)
    {
        var table = language == InterfaceLanguage.SimplifiedChinese ? Zh : En;
        if (!table.TryGetValue(key, out var template) && !En.TryGetValue(key, out template)) return key;
        if (args.Length == 0) return template;
        // Only {n} is a placeholder, so text such as {apiKey} can appear literally.
        return Placeholder().Replace(template, m =>
        {
            var i = int.Parse(m.Groups[1].Value);
            return i < args.Length ? Convert.ToString(args[i], System.Globalization.CultureInfo.InvariantCulture) ?? string.Empty : m.Value;
        });
    }

